"""Bounded G=2 vector-only prototype; scalar WORK and per-row reduction tree unchanged."""
import triton as tr
import triton.language as tl
@tr.jit
def vector_kernel(CO,MEAN,DETAIL,MASK,MAP,WORK,STATE,CAND,T:tl.constexpr,M:tl.constexpr,P:tl.constexpr,K:tl.constexpr,S:tl.constexpr,NS:tl.constexpr,VD:tl.constexpr=16,VP:tl.constexpr=False):
    row=tl.program_id(0)*2;b=row//M;head=b//T;shard=tl.program_id(1)
    p=shard*S+tl.arange(0,S);d=tl.arange(0,16)
    off=(row*NS+shard)*10*S+tl.arange(0,S)
    off1=off+NS*10*S
    base=CO+head*P*85+p[:,None]*85+d[None,:]
    f0=tl.load(WORK+off+0*S);g0=tl.load(WORK+off1+0*S)
    f1=tl.load(WORK+off+1*S);g1=tl.load(WORK+off1+1*S)
    f2=tl.load(WORK+off+2*S);g2=tl.load(WORK+off1+2*S)
    f3=tl.load(WORK+off+3*S);g3=tl.load(WORK+off1+3*S)
    a=tl.load(base+17*1,p[:,None]<P,0).to(tl.float32)
    rp0=f0[:,None]*a
    rp1=g0[:,None]*a
    a=tl.load(base+17*2,p[:,None]<P,0).to(tl.float32)
    rp0=rp0+f1[:,None]*a
    rp1=rp1+g1[:,None]*a
    a=tl.load(base+17*3,p[:,None]<P,0).to(tl.float32)
    rp0=rp0+f2[:,None]*a
    rp1=rp1+g2[:,None]*a
    a=tl.load(base+17*4,p[:,None]<P,0).to(tl.float32)
    rp0=rp0+f3[:,None]*a
    rp1=rp1+g3[:,None]*a
    a=tl.load(base,p[:,None]<P,0).to(tl.float32)
    rp0=rp0+a;rp1=rp1+a
    db=DETAIL+head*P*48+p[:,None]*48+d[None,:]
    a=tl.load(db+0*16,p[:,None]<P,0).to(tl.float32)
    c0=tl.load(WORK+off+4*S);c1=tl.load(WORK+off1+4*S)
    center0=c0[:,None]*a
    center1=c1[:,None]*a
    a=tl.load(db+1*16,p[:,None]<P,0).to(tl.float32)
    c0=tl.load(WORK+off+5*S);c1=tl.load(WORK+off1+5*S)
    center0=center0+c0[:,None]*a
    center1=center1+c1[:,None]*a
    a=tl.load(db+2*16,p[:,None]<P,0).to(tl.float32)
    c0=tl.load(WORK+off+6*S);c1=tl.load(WORK+off1+6*S)
    center0=center0+c0[:,None]*a
    center1=center1+c1[:,None]*a
    a=tl.load(MEAN+head*P*16+p[:,None]*16+d[None,:],p[:,None]<P,0).to(tl.float32)
    center0=center0+a;center1=center1+a
    selected=tl.load(MASK+b*P+p,p<P,0);slot=tl.load(MAP+b*P+p,p<P,-1)
    wc=tl.load(WORK+off+7*S);wt=tl.load(WORK+off+8*S);wb=tl.load(WORK+off+9*S)
    current=center0+tl.where(selected[:,None],rp0,0.)
    h=tl.sum(wc[:,None]*current,0);target=tl.sum(wt[:,None]*(center0+rp0),0);ob=tl.sum(wb[:,None]*current,0)
    tl.store(STATE+((row+0)*NS+shard)*48+d,h)
    tl.store(STATE+((row+0)*NS+shard)*48+16+d,target)
    tl.store(STATE+((row+0)*NS+shard)*48+32+d,ob)
    cp=CAND+((row+0)*K+slot)*34;valid=(p<P)&(slot>=0)
    tl.store(cp[:,None]+2+d[None,:],center0,valid[:,None])
    tl.store(cp[:,None]+18+d[None,:],rp0,valid[:,None])
    wc=tl.load(WORK+off1+7*S);wt=tl.load(WORK+off1+8*S);wb=tl.load(WORK+off1+9*S)
    current=center1+tl.where(selected[:,None],rp1,0.)
    h=tl.sum(wc[:,None]*current,0);target=tl.sum(wt[:,None]*(center1+rp1),0);ob=tl.sum(wb[:,None]*current,0)
    tl.store(STATE+((row+1)*NS+shard)*48+d,h)
    tl.store(STATE+((row+1)*NS+shard)*48+16+d,target)
    tl.store(STATE+((row+1)*NS+shard)*48+32+d,ob)
    cp=CAND+((row+1)*K+slot)*34;valid=(p<P)&(slot>=0)
    tl.store(cp[:,None]+2+d[None,:],center1,valid[:,None])
    tl.store(cp[:,None]+18+d[None,:],rp1,valid[:,None])
