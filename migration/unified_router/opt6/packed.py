"""Same FP32 action math as fast_features; statistics and only the 16 candidate contents are precomputed."""
import math
import triton as tr
import triton.language as tl
from triton.language.extra.cuda.libdevice import erf

@tr.jit
def _packed_actions(ST, X, V, S, C, O, R, A, W1, B1, W2, B2, MU, SIG, STEP, OUT, N: tl.constexpr, B: tl.constexpr, P: tl.constexpr, HIST: tl.constexpr, CUR: tl.constexpr, BETA: tl.constexpr, PRECISION: tl.constexpr):
    row = tl.program_id(0)
    head = row // N
    p = tl.arange(0, P)
    d = tl.arange(0, 32)
    a = tl.arange(0, 128)
    hidden = tl.arange(0, 16)
    selected = tl.load(S + row * B + p, p < B, False)
    total = tl.load(ST + row * 80 + d)
    center = tl.load(ST + row * 80 + 32 + d)
    av = center - total
    ds = tl.load(ST + row * 80 + 64)
    da = tl.load(ST + row * 80 + 65)
    mean = tl.load(ST + row * 80 + 66)
    std = tl.load(ST + row * 80 + 67)
    scost = tl.load(ST + row * 80 + 68)
    cost = tl.load(ST + row * 80 + 69)
    current_cost = tl.load(ST + row * 80 + 70)
    nselected = tl.load(ST + row * 80 + 71).to(tl.int32)
    meanz = tl.load(ST + row * 80 + 72)
    remove_slot = tl.where(a < 17, a - 9, (a - 17) // 8)
    add_slot = tl.where(a < 9, a - 1, (a - 17) % 8)
    i = tl.load(R + row * 8 + remove_slot, (a >= 9) & (a < 81), -1)
    j = tl.load(A + row * 8 + add_slot, (a >= 1) & (a <= 8) | (a >= 17) & (a < 81), -1)
    vi = tl.load(V + (row * 16 + remove_slot[:, None]) * 32 + d[None, :], i[:, None] >= 0, 0.0)
    vj = tl.load(V + (row * 16 + 8 + add_slot[:, None]) * 32 + d[None, :], j[:, None] >= 0, 0.0)
    xi = tl.where(i[:, None] >= 0, vi - center[None, :], 0.0)
    xj = tl.where(j[:, None] >= 0, vj - center[None, :], 0.0)
    g0 = tl.sum(av * av, 0)
    g1 = tl.sum(xi * xi, 1)
    g2 = tl.sum(xj * xj, 1)
    g3 = tl.sum(av[None, :] * xi, 1)
    g4 = tl.sum(av[None, :] * xj, 1)
    g5 = tl.sum(xi * xj, 1)
    zi = tl.where(i >= 0, (tl.load(X + row * B + i, i >= 0, 0.0) - mean) / std, 0.0)
    zj = tl.where(j >= 0, (tl.load(X + row * B + j, j >= 0, 0.0) - mean) / std, 0.0)
    ci = tl.load(C + i, i >= 0, 0.0)
    cj = tl.load(C + j, j >= 0, 0.0)
    oi = tl.load(O + i, i >= 0, 0.0)
    oj = tl.load(O + j, j >= 0, 0.0)
    
    step = tl.load(STEP)
    f0 = tl.broadcast_to(g0, (128,))
    f1 = tl.broadcast_to(g1, (128,))
    f2 = tl.broadcast_to(g2, (128,))
    f3 = tl.broadcast_to(g3, (128,))
    f4 = tl.broadcast_to(g4, (128,))
    f5 = tl.broadcast_to(g5, (128,))
    f6 = tl.broadcast_to(ds, (128,))
    f7 = tl.broadcast_to(da, (128,))
    f8 = tl.broadcast_to(zi, (128,))
    f9 = tl.broadcast_to(zj, (128,))
    f10 = tl.broadcast_to(tl.log(std), (128,))
    f11 = tl.full((128,),BETA,tl.float32)
    f12 = tl.broadcast_to(scost / cost, (128,))
    f13 = tl.broadcast_to(current_cost / CUR, (128,))
    f14 = tl.full((128,),math.log1p(HIST),tl.float32)
    f15 = tl.full((128,),math.log1p(CUR),tl.float32)
    f16 = tl.broadcast_to(step / 3.0, (128,))
    f17 = tl.broadcast_to(ci / 64.0, (128,))
    f18 = tl.broadcast_to(cj / 64.0, (128,))
    f19 = tl.broadcast_to((i >= 0).to(tl.float32), (128,))
    f20 = tl.broadcast_to((j >= 0).to(tl.float32), (128,))
    f21 = tl.broadcast_to(oi, (128,))
    f22 = tl.broadcast_to(oj, (128,))
    f23 = tl.broadcast_to(meanz, (128,))
    f24 = tl.full((128,),0.0,tl.float32)
    f25 = tl.full((128,),0.0,tl.float32)
    f26 = tl.full((128,),0.0,tl.float32)
    f27 = tl.full((128,),0.0,tl.float32)
    f28 = tl.full((128,),0.0,tl.float32)
    f29 = tl.full((128,),0.0,tl.float32)
    f30 = tl.full((128,),0.0,tl.float32)
    f31 = tl.full((128,),0.0,tl.float32)
    pack0_0 = tl.join(f0, f16)
    pack0_1 = tl.join(f8, f24)
    pack0_2 = tl.join(f4, f20)
    pack0_3 = tl.join(f12, f28)
    pack0_4 = tl.join(f2, f18)
    pack0_5 = tl.join(f10, f26)
    pack0_6 = tl.join(f6, f22)
    pack0_7 = tl.join(f14, f30)
    pack0_8 = tl.join(f1, f17)
    pack0_9 = tl.join(f9, f25)
    pack0_10 = tl.join(f5, f21)
    pack0_11 = tl.join(f13, f29)
    pack0_12 = tl.join(f3, f19)
    pack0_13 = tl.join(f11, f27)
    pack0_14 = tl.join(f7, f23)
    pack0_15 = tl.join(f15, f31)
    pack1_0 = tl.join(pack0_0, pack0_1)
    pack1_1 = tl.join(pack0_2, pack0_3)
    pack1_2 = tl.join(pack0_4, pack0_5)
    pack1_3 = tl.join(pack0_6, pack0_7)
    pack1_4 = tl.join(pack0_8, pack0_9)
    pack1_5 = tl.join(pack0_10, pack0_11)
    pack1_6 = tl.join(pack0_12, pack0_13)
    pack1_7 = tl.join(pack0_14, pack0_15)
    pack2_0 = tl.join(pack1_0, pack1_1)
    pack2_1 = tl.join(pack1_2, pack1_3)
    pack2_2 = tl.join(pack1_4, pack1_5)
    pack2_3 = tl.join(pack1_6, pack1_7)
    pack3_0 = tl.join(pack2_0, pack2_1)
    pack3_1 = tl.join(pack2_2, pack2_3)
    pack4_0 = tl.join(pack3_0, pack3_1)
    f = pack4_0.reshape((128,32))
    mu = tl.load(MU + head * 24 + d, d < 24, 0.0)
    sig = tl.load(SIG + head * 24 + d, d < 24, 1.0)
    f = (f - mu[None, :]) / sig[None, :]
    w = tl.load(W1 + head * 16 * 24 + hidden[None, :] * 24 + d[:, None], d[:, None] < 24, 0.0)
    b = tl.load(B1 + head * 16 + hidden)
    if PRECISION == 'fp16':
        y = tl.dot(f.to(tl.float16), w.to(tl.float16)) + b[None, :]
    else:
        y = tl.dot(f, w, input_precision=PRECISION) + b[None, :]
    y = 0.5 * y * (1.0 + erf(y * 0.7071067811865476))
    w2 = tl.load(W2 + head * 16 + hidden)
    b2 = tl.load(B2 + head)
    pred = tl.sum(y * w2[None, :], 1) + b2
    valid = (a == 0) | (a >= 1) & (a <= 8) & (j >= 0) | (a >= 9) & (a <= 16) & (i >= 0) & (nselected > 1) | (a >= 17) & (a < 81) & (i >= 0) & (j >= 0)
    pred = tl.where(a == 0, 0.0, tl.where(valid, pred, float('-inf')))
    best = tl.max(pred, 0)
    chosen = tl.min(tl.where(pred == best, a, 2147483647), 0)
    ri = tl.sum(tl.where(a == chosen, i, 0), 0)
    aj = tl.sum(tl.where(a == chosen, j, 0), 0)
    final = selected & (p != ri) | (p == aj)
    tl.store(OUT + row * B + p, final, p < B)
